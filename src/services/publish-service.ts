/**
 * The APIM Backend properties.type value that identifies a pool backend.
 * Pool backends reference other Backend resources and must be published
 * after the individual backends they aggregate.
 */
const POOL_BACKEND_TYPE = 'pool';

export interface PublishActionResult {
  descriptor: ResourceDescriptor;
  action: 'put' | 'patch' | 'delete' | 'noop';
  status: 'success' | 'failed' | 'skipped';
  error?: Error;
  /** Number of HTTP retries performed while processing this resource. */
  retries?: number;
}

export interface PublishResult {
  totalPuts: number;
  totalPatches: number;
  totalDeletes: number;
  totalErrors: number;
  totalSkipped: number;
  exitCode: number; // 0=success, 1=partial failure, 2=fatal
  actions: PublishActionResult[];
  dryRunReport?: DryRunReport;
  /** Wall-clock duration of the publish run in milliseconds. */
  elapsedMs?: number;
  /** Total HTTP retries performed across all resources. */
  totalRetries?: number;
  /** Number of resources that required at least one retry. */
  retriedResources?: number;
}

interface PublishTargets {
  targetDescriptors: ResourceDescriptor[];
  deletedDescriptors: ResourceDescriptor[];
}

/**
 * Main publish orchestration function.
 * Coordinates PUT/DELETE operations across dependency tiers and reports
 * elapsed time and retry statistics.
 */
export async function runPublish(
  client: IApimClient,
  store: IArtifactStore,
  config: PublishConfig
): Promise<PublishResult> {
  const startedAt = Date.now();
  const result = await runPublishPipeline(client, store, config);
  const retriedActions = result.actions.filter((action) => (action.retries ?? 0) > 0);
  return {
    ...result,
    elapsedMs: Date.now() - startedAt,
    totalRetries: retriedActions.reduce((sum, action) => sum + (action.retries ?? 0), 0),
    retriedResources: retriedActions.length,
  };
}

async function runPublishPipeline(
  client: IApimClient,
  store: IArtifactStore,
  config: PublishConfig
): Promise<PublishResult> {
  try {
    // Step 0: Pre-flight validation — ensure the resource group and APIM service exist
    await client.validatePreFlight(config.service);

    // The named values policies use as resource names, read from the source
    // once for this run when the expansion or the Tier 1 order first needs it.
    const namedValueTargets = createNamedValueTargetIndex(store, config);

    // Step 1: Determine target descriptors based on incremental mode
    const { targetDescriptors, deletedDescriptors } = await determinePublishTargets(
      store,
      config,
      namedValueTargets
    );

    // Step 1a: For env-mapping validation and policy ref rewriting we need
    // the FULL artifact set, not just the changed subset returned by
    // incremental mode. Cross-references (policy tokens, fragment/backend
    // refs) can point at named values / fragments / backends whose files
    // didn't change in this commit — those must still be rewritten.
    // Stale-override warnings likewise need the full set to avoid firing on
    // every unchanged artifact in incremental runs.
    const allDescriptors = config.commitId
      ? await store.listResources(config.sourceDir)
      : targetDescriptors;

    // Step 1b: Validate env mapping and store it on config for downstream use
    validateAndBuildEnvMapping(config.overrides, allDescriptors, config);

    // Step 1c: Build known artifact sets for policy ref rewriting
    config.knownArtifactSets = buildKnownArtifactSets(allDescriptors);

    logger.debug(
      `Publishing ${targetDescriptors.length} resources (dry-run: ${config.dryRun})`
    );

    // Step 1c: Redaction pre-flight gate.
    // Scan every artifact that would be published for leftover redaction markers
    // ('*** REDACTED ***'). A single leftover marker aborts the ENTIRE publish
    // before any PUT is issued — and also fails dry-run — so a service can never
    // be left partially published with placeholder secrets.
    const redactionFindings = await scanForRedactionMarkers(
      store,
      config,
      targetDescriptors
    );
    if (redactionFindings.length > 0) {
      logger.error(
        `Publish aborted: ${redactionFindings.length} artifact(s) still contain the redaction marker '${REDACTION_MARKER}'. ` +
        'Replace inline secrets with named values or KeyVault references before publishing: ' +
        'https://learn.microsoft.com/en-us/azure/api-management/api-management-howto-properties'
      );
      const actions: PublishActionResult[] = redactionFindings.map((finding) => {
        logger.error(`  - ${finding.label} (${finding.location})`);
        return {
          descriptor: finding.descriptor,
          action: 'noop',
          status: 'failed',
          error: new Error(
            `${finding.label} contains '${REDACTION_MARKER}' in ${finding.location}`
          ),
        };
      });

      return {
        totalPuts: 0,
        totalPatches: 0,
        totalDeletes: 0,
        totalErrors: actions.length,
        totalSkipped: 0,
        exitCode: EXIT_FATAL,
        actions,
      };
    }

    // Step 2: Handle dry-run mode
    if (config.dryRun) {
      const dryRunReport = await generateDryRunReport(
        store,
        client,
        config.service,
        config,
        targetDescriptors,
        config.deleteUnmatched ? deletedDescriptors : []
      );
      const totalErrors = dryRunReport.actions.filter((action) => action.error).length;

      return {
        totalPuts: dryRunReport.summary.creates,
        totalPatches: dryRunReport.summary.patches,
        totalDeletes: dryRunReport.summary.deletes,
        totalErrors,
        totalSkipped: dryRunReport.summary.skips,
        exitCode: totalErrors > 0 ? EXIT_PARTIAL : EXIT_SUCCESS,
        actions: [],
        dryRunReport,
      };
    }

    // Step 3: Execute PUTs in dependency order (tier 1 → tier 4)
    const putResults = await executePuts(
      client,
      store,
      config.service,
      config,
      targetDescriptors,
      namedValueTargets
    );

    // Step 4: Execute DELETEs in reverse dependency order (tier 4 → tier 1) if requested
    let deleteResults: PublishActionResult[] = [];
    if (config.deleteUnmatched && deletedDescriptors.length > 0) {
      deleteResults = await executeDeletesForDescriptors(
        client,
        config.service,
        deletedDescriptors,
        config
      );
    } else if (config.deleteUnmatched && !config.commitId) {
      deleteResults = await executeDeletes(
        client,
        store,
        config.service,
        config
      );
    }

    // Step 5: Combine results and determine exit code
    const allResults = [...putResults, ...deleteResults];
    const totalPuts = putResults.filter((result) => result.action === 'put').length;
    const totalPatches = putResults.filter((result) => result.action === 'patch').length;
    const totalDeletes = deleteResults.length;
    const totalErrors = allResults.filter((r) => r.status === 'failed').length;
    const totalSkipped = allResults.filter((r) => r.status === 'skipped').length;

    const exitCode = determineExitCode(allResults);

    return {
      totalPuts,
      totalPatches,
      totalDeletes,
      totalErrors,
      totalSkipped,
      exitCode,
      actions: allResults,
    };
  } catch (error) {
    logger.error('Fatal error during publish:', error);
    return {
      totalPuts: 0,
      totalPatches: 0,
      totalDeletes: 0,
      totalErrors: 1,
      totalSkipped: 0,
      exitCode: EXIT_FATAL,
      actions: [],
    };
  }
}

/**
 * Determine which resources to publish based on incremental mode.
 */
async function determinePublishTargets(
  store: IArtifactStore,
  config: PublishConfig,
  namedValueTargets: NamedValueTargetIndex
): Promise<PublishTargets> {
  let targetDescriptors: ResourceDescriptor[];
  let deletedDescriptors: ResourceDescriptor[];

  if (config.commitId) {
    // Incremental mode: use git diff
    logger.debug(
      `Using incremental publish mode with commit ID: ${config.commitId}`
    );
    const diffResult = await computeGitDiff(config.sourceDir, config.commitId);
    targetDescriptors = diffResult.changedDescriptors;
    deletedDescriptors = diffResult.deletedDescriptors;
  } else {
    // Full mode: publish all artifacts
    logger.debug('Using full publish mode (all artifacts)');
    targetDescriptors = await store.listResources(config.sourceDir);
    deletedDescriptors = [];
  }

  targetDescriptors = filterPublishDescriptors(targetDescriptors, config.filter);
  deletedDescriptors = filterPublishDescriptors(deletedDescriptors, config.filter);

  if (config.filter && config.includeTransitive !== false) {
    const availableDescriptors = await store.listResources(config.sourceDir);
    targetDescriptors = await expandTransitivePublishTargets(
      store,
      config.sourceDir,
      targetDescriptors,
      availableDescriptors,
      config.filter,
      config.overrides,
      namedValueTargets
    );
  }

  return { targetDescriptors, deletedDescriptors };
}

/**
 * The resource types each named value in the source is used for as a resource
 * name (indexNamedValueTargetTypes over every policy and policy fragment):
 * built on first use and then shared, so a publish run reads the policies once
 * for both the transitive expansion and the Tier 1 order.
 */
type NamedValueTargetIndex = () => Promise<Map<string, Set<ResourceType>>>;

function createNamedValueTargetIndex(store: IArtifactStore, config: PublishConfig): NamedValueTargetIndex {
  let index: Promise<Map<string, Set<ResourceType>>> | undefined;
  return () => {
    index ??= store.listResources(config.sourceDir).then((available) =>
      indexNamedValueTargetTypes(
        store,
        config.sourceDir,
        available,
        available,
        createArtifactReferenceResolver(available, (descriptor) => store.readResource(config.sourceDir, descriptor))
      )
    );
    return index;
  };
}

async function expandTransitivePublishTargets(
  store: IArtifactStore,
  sourceDir: string,
  initialDescriptors: ResourceDescriptor[],
  availableDescriptors: ResourceDescriptor[],
  filter: FilterConfig,
  overrides: OverrideConfig | undefined,
  namedValueTargets: NamedValueTargetIndex
): Promise<ResourceDescriptor[]> {
  const findAvailable = createArtifactReferenceResolver(
    availableDescriptors,
    (descriptor) => store.readResource(sourceDir, descriptor)
  );
  // A named value as it is published: with this environment's overrides,
  // which can name a different resource. One that can't be read only hides
  // what a policy attribute set to it names; publishing the named value
  // reports the error. One the filter excludes isn't published, so neither
  // is what it names.
  const readNamedValueJson = async (descriptor: ResourceDescriptor) => {
    if (isExplicitlyExcluded(descriptor, filter)) {
      return undefined;
    }
    try {
      const json = await store.readResource(sourceDir, descriptor);
      return json ? applyOverrides(descriptor, json, overrides) : undefined;
    } catch (error) {
      logger.warn(`Unable to read ${buildResourceLabel(descriptor)} to find what policies set to it name: ${String(error)}`);
      return undefined;
    }
  };
  const readNamedValue = createNamedValueReader(findAvailable, readNamedValueJson);
  // A published named value needs the resource its value names when any
  // policy or fragment in the source uses it as a resource name
  // (backend-id="{{name}}"), even one the filter leaves out: APIM checks every
  // policy on the target that uses a named value when the named value
  // changes, and rejects the change while the resource it names is missing.
  // The policies are read once per run, on the first named value in the
  // publish set.
  const findNamedValueTargets = async (namedValue: ResourceDescriptor): Promise<ResourceDescriptor[]> => {
    const types = (await namedValueTargets()).get(getResourceDescriptorKey(namedValue));
    const json = types ? await readNamedValueJson(namedValue) : undefined;
    const name = json ? namedValueTargetName(json) : undefined;
    return types && name
      ? [...types].map((type) => ({ type, nameParts: [name], workspace: namedValue.workspace }))
      : [];
  };
  const expanded = [...initialDescriptors];
  const included = new Set(expanded.map(getResourceDescriptorKey));
  const scanQueue = [...initialDescriptors];
  const scanQueued = new Set(scanQueue.map(getResourceDescriptorKey));

  // A changed API or product info file can be the only diff entry even when
  // its policy/association artifacts contain the references to resolve.
  for (const descriptor of initialDescriptors) {
    if (descriptor.type !== ResourceType.Api && descriptor.type !== ResourceType.Product) {
      continue;
    }
    if (
      descriptor.type === ResourceType.Api &&
      isApiRevisionName(descriptor.nameParts[0] ?? '')
    ) {
      continue;
    }
    const parentName = descriptor.type === ResourceType.Api
      ? extractRootApiName(descriptor.nameParts[0] ?? '').toLowerCase()
      : (descriptor.nameParts[0] ?? '').toLowerCase();
    for (const candidate of availableDescriptors) {
      const isSameResourceType = candidate.type === descriptor.type;
      const isOwnedChild = getParentType(candidate.type) === descriptor.type;
      if (
        (!isSameResourceType && !isOwnedChild) ||
        candidate.workspace !== descriptor.workspace ||
        candidate.nameParts.length < 1 ||
        !shouldReconcileResource(candidate, filter)
      ) {
        continue;
      }
      const candidateName = candidate.type === ResourceType.Api
        ? extractRootApiName(candidate.nameParts[0] ?? '').toLowerCase()
        : (candidate.nameParts[0] ?? '').toLowerCase();
      if (candidateName === parentName) {
        const candidateKey = getResourceDescriptorKey(candidate);
        if (!included.has(candidateKey)) {
          included.add(candidateKey);
          expanded.push(candidate);
        }
        if (!scanQueued.has(candidateKey)) {
          scanQueue.push(candidate);
          scanQueued.add(candidateKey);
        }
      }
    }
  }

  for (let index = 0; index < scanQueue.length; index++) {
    let references: ResourceDescriptor[];
    try {
      // As published: an override can change what a backend's or logger's
      // credentials or a diagnostic's logger reference.
      references = await scanArtifactReferences(
        store, sourceDir, scanQueue[index], readNamedValue,
        (descriptor, json) => applyOverrides(descriptor, json, overrides)
      );
      if (scanQueue[index].type === ResourceType.NamedValue) {
        references.push(...await findNamedValueTargets(scanQueue[index]));
      }
    } catch (error) {
      logger.warn(
        `Unable to scan transitive references for ${scanQueue[index].type} "${scanQueue[index].nameParts.join('/')}": ${String(error)}`
      );
      continue;
    }
    for (const reference of references) {
      const available = await findAvailable(reference);
      if (
        available &&
        !included.has(getResourceDescriptorKey(available)) &&
        !isExplicitlyExcluded(available, filter)
      ) {
        included.add(getResourceDescriptorKey(available));
        expanded.push(available);
        scanQueue.push(available);
      }
    }
  }

  if (expanded.length > initialDescriptors.length) {
    logger.debug(
      `Transitive publish resolution added ${expanded.length - initialDescriptors.length} resources`
    );
  }
  return expanded;
}

function filterPublishDescriptors(
  descriptors: ResourceDescriptor[],
  filter?: FilterConfig
): ResourceDescriptor[] {
  if (!filter) {
    return descriptors;
  }

  return descriptors.filter((descriptor) => {
    if (descriptor.type === ResourceType.Workspace) {
      return matchesWorkspaceName(descriptor.nameParts[0] ?? '', filter.workspaces);
    }

    if (!descriptor.workspace) {
      return shouldIncludeResource(descriptor, filter);
    }

    if (!matchesWorkspaceName(descriptor.workspace, filter.workspaces)) {
      return false;
    }

    const workspaceFilter = resolveWorkspaceFilter(descriptor.workspace, filter);
    return shouldIncludeResource(descriptor, workspaceFilter ?? undefined);
  });
}

function matchesWorkspaceName(name: string, allowlist: string[] | undefined): boolean {
  if (allowlist === undefined) {
    return true;
  }

  return shouldIncludeResource(
    { type: ResourceType.Workspace, nameParts: [name] },
    { workspaces: allowlist }
  );
}

/**
 * Execute PUT operations in dependency order (tier 1 → tier 4).
 */
async function executePuts(
  client: IApimClient,
  store: IArtifactStore,
  context: ApimServiceContext,
  config: PublishConfig,
  targetDescriptors: ResourceDescriptor[],
  namedValueTargets: NamedValueTargetIndex
): Promise<PublishActionResult[]> {
  const results: PublishActionResult[] = [];

  // Group descriptors by tier
  const tierGroups = new Map<number, ResourceDescriptor[]>();
  for (const descriptor of targetDescriptors) {
    const tier = getResourceTier(descriptor.type);
    if (!tierGroups.has(tier)) {
      tierGroups.set(tier, []);
    }
    tierGroups.get(tier)!.push(descriptor);
  }

  // Build a map of parent type → Set of parent names being published in tier 2.
  // Top-level types (not child types) handle their children internally,
  // so we exclude those children from tiers 3/4 to avoid double-publishing.
  const parentNamesByType = new Map<ResourceType, Set<string>>();
  for (const d of tierGroups.get(2) || []) {
    // Top-level singletons such as ServicePolicy do not participate in
    // parent-name child filtering.
    if (isTopLevelSingleton(d.type)) {
      continue;
    }

    // Top-level types are those that are NOT child types
    if (!isChildType(d.type)) {
      if (!parentNamesByType.has(d.type)) {
        parentNamesByType.set(d.type, new Set());
      }
      parentNamesByType.get(d.type)!.add(parentScopeKey(d));
    }
  }

  // Execute each tier in order (1, 2, 3, 4)
  for (const tier of [1, 2, 3, 4]) {
    const descriptors = tierGroups.get(tier) || [];
    if (descriptors.length === 0) continue;

    logger.debug(`Publishing tier ${tier}: ${descriptors.length} resources`);
    const tierStartedAt = Date.now();

    if (tier === 1) {
      const { workspaces, nonWorkspaceTier1 } = splitWorkspaces(descriptors);
      const { namedValues, otherTier1 } = splitNamedValues(nonWorkspaceTier1, config.overrides);
      const tierCount = workspaces.length + namedValues.length + otherTier1.length;
      if (tierCount === 0) continue;
      writeTierHeader(config, tier, tierCount);

      if (workspaces.length > 0) {
        logger.debug(`Publishing ${workspaces.length} workspace container(s) first (wave 0 of tier 1)`);
        await publishAndOutput(client, store, context, config, workspaces, targetDescriptors, results);
      }

      // Within Tier 1 we publish in ordered waves to satisfy implicit
      // runtime dependencies:
      //
      // Wave 1 — Named values, except those in wave 4.
      //   Loggers and backends may reference named values by name in their
      //   configuration (e.g. AppInsights instrumentation key stored as a
      //   named value). Publishing named values first ensures they exist
      //   before any resource that references them.
      //
      // Wave 2 — The remaining Tier 1 resources except pool backends and
      //   wave 5 (and except policy fragments when wave 4 has named values).
      //
      // Wave 3 — Pool backends.
      //   Pool backends reference individual Backend resources and must be
      //   published after the backends they aggregate (see pool backend
      //   ordering comments in splitPoolBackends).
      //
      // Wave 4 — Named values a policy uses as a resource name
      //   (backend-id="{{name}}") whose value names a backend, logger or
      //   schema published here. APIM checks the policies that use a named
      //   value when it changes, so that resource must exist first (see
      //   splitNamedValuesNamingResources).
      //
      // Wave 5 — Backends and loggers whose credentials use a wave 4 named
      //   value, when they don't have to go before one.
      //
      // Wave 6 — Policy fragments, when wave 4 has named values: a fragment
      //   can use them, and APIM rejects a policy that uses a missing one.
      const { early: earlyNamedValues, late: lateNamedValues, after: afterLateNamedValues } = await splitNamedValuesNamingResources(
        store,
        config,
        namedValues,
        otherTier1,
        namedValueTargets
      );
      if (earlyNamedValues.length > 0) {
        logger.debug(`Publishing ${earlyNamedValues.length} named value(s) first (wave 1 of tier 1)`);
        await publishAndOutput(client, store, context, config, earlyNamedValues, targetDescriptors, results);
      }

      const { poolBackends, regularTier1 } = await splitPoolBackends(
        store,
        config.sourceDir,
        otherTier1.filter((descriptor) => !afterLateNamedValues.includes(descriptor))
      );
      const fragments = lateNamedValues.length > 0
        ? regularTier1.filter((descriptor) => descriptor.type === ResourceType.PolicyFragment)
        : [];
      await publishAndOutput(
        client,
        store,
        context,
        config,
        regularTier1.filter((descriptor) => !fragments.includes(descriptor)),
        targetDescriptors,
        results
      );
      if (poolBackends.length > 0) {
        logger.debug(
          `Publishing ${poolBackends.length} pool backend(s) after regular backends`
        );
        await publishAndOutput(
          client,
          store,
          context,
          config,
          poolBackends,
          targetDescriptors,
          results
        );
      }
      if (lateNamedValues.length > 0) {
        logger.debug(
          `Publishing ${lateNamedValues.length} named value(s) after the resources their values name`
        );
        await publishAndOutput(client, store, context, config, lateNamedValues, targetDescriptors, results);
      }
      if (afterLateNamedValues.length > 0) {
        await publishAndOutput(client, store, context, config, afterLateNamedValues, targetDescriptors, results);
      }
      if (fragments.length > 0) {
        await publishAndOutput(client, store, context, config, fragments, targetDescriptors, results);
      }
    } else if (tier === 2) {
      const tier2Descriptors = filterApiRevisionsHandledByRootApis(descriptors);
      if (tier2Descriptors.length === 0) continue;
      writeTierHeader(config, tier, tier2Descriptors.length);
      const apiDescriptors = tier2Descriptors.filter((d) => d.type === ResourceType.Api);
      const nonApiDescriptors = tier2Descriptors.filter((d) => d.type !== ResourceType.Api);

      const { mcpApis, regularTier2: regularApis } = await splitMcpApis(
        store,
        config.sourceDir,
        apiDescriptors
      );

      await publishAndOutput(client, store, context, config, regularApis, targetDescriptors, results);

      if (mcpApis.length > 0) {
        logger.debug(`Publishing ${mcpApis.length} MCP API resource(s) after regular tier 2 resources`);
        await publishAndOutput(client, store, context, config, mcpApis, targetDescriptors, results);
      }

      await publishAndOutput(client, store, context, config, nonApiDescriptors, targetDescriptors, results);
    } else {
      // For tiers 3/4, exclude child resources whose parent is being published
      // in tier 2 (publishApi/publishProduct handle their children internally).
      // Use getParentType() to dynamically determine parent-child relationships.
      let tierDescriptors = descriptors;

      if (parentNamesByType.size > 0) {
        const countBefore = tierDescriptors.length;
        tierDescriptors = tierDescriptors.filter((d) => {
          // Top-level types have no parent to check
          if (!isChildType(d.type)) return true;

          // Child resources have the parent name as nameParts[0]
          const parentType = getParentType(d.type);
          if (!parentType) return true;

          return !parentNamesByType.get(parentType)?.has(parentScopeKey(d));
        });
        const skipped = countBefore - tierDescriptors.length;
        if (skipped > 0) {
          logger.debug(`Skipping ${skipped} child resource(s) in tier ${tier} (handled by parent publisher)`);
        }

      }

      if (tierDescriptors.length === 0) continue;
      writeTierHeader(config, tier, tierDescriptors.length);
      await publishAndOutput(client, store, context, config, tierDescriptors, targetDescriptors, results);
    }

    writeTierFooter(config, tier, Date.now() - tierStartedAt);
  }

  return results;
}

/**
 * True when human-readable text may be written to stdout.
 * In `--format json` mode stdout must carry only the JSON document, so all
 * service-level text output is suppressed.
 */
function isTextOutput(config: PublishConfig): boolean {
  return config.outputFormat !== 'json';
}

/**
 * Write a tier header line to stdout, e.g.
 * `── Tier 1: Independent resources (16) ──`.
 */
function writeTierHeader(
  config: PublishConfig,
  tier: number,
  count: number,
  prefix = 'Tier'
): void {
  if (!isTextOutput(config)) return;
  const label = TIER_LABELS[tier] ?? 'Resources';
  process.stdout.write(`\n── ${prefix} ${tier}: ${label} (${count}) ──\n`);
}

/**
 * Write the per-tier completion line with elapsed time to stdout.
 */
function writeTierFooter(
  config: PublishConfig,
  tier: number,
  elapsedMs: number,
  prefix = 'Tier'
): void {
  if (!isTextOutput(config)) return;
  process.stdout.write(`${prefix} ${tier} completed in ${formatDuration(elapsedMs)}\n`);
}

function parentScopeKey(descriptor: ResourceDescriptor): string {
  return `${descriptor.workspace ?? ''}:${getNamePart(descriptor.nameParts, 0)}`.toLowerCase();
}

function getParentType(type: ResourceType): ResourceType | undefined {
  if (
    [
      ResourceType.ApiPolicy,
      ResourceType.ApiTag,
      ResourceType.ApiDiagnostic,
      ResourceType.ApiOperation,
      ResourceType.ApiOperationPolicy,
      ResourceType.ApiSchema,
      ResourceType.ApiRelease,
      ResourceType.ApiTagDescription,
      ResourceType.ApiWiki,
      ResourceType.GraphQLResolver,
      ResourceType.GraphQLResolverPolicy,
    ].includes(type)
  ) {
    return ResourceType.Api;
  }

  if (
    [
      ResourceType.ProductPolicy,
      ResourceType.ProductApi,
      ResourceType.ProductGroup,
      ResourceType.ProductTag,
      ResourceType.ProductWiki,
    ].includes(type)
  ) {
    return ResourceType.Product;
  }

  if (type === ResourceType.GatewayApi) {
    return ResourceType.Gateway;
  }

  return undefined;
}

function splitWorkspaces(
  descriptors: ResourceDescriptor[]
): { workspaces: ResourceDescriptor[]; nonWorkspaceTier1: ResourceDescriptor[] } {
  const workspaces: ResourceDescriptor[] = [];
  const nonWorkspaceTier1: ResourceDescriptor[] = [];

  for (const descriptor of descriptors) {
    if (descriptor.type === ResourceType.Workspace) {
      workspaces.push(descriptor);
    } else {
      nonWorkspaceTier1.push(descriptor);
    }
  }

  return { workspaces, nonWorkspaceTier1 };
}

/**
 * Publish a batch of descriptors and write their status lines to stdout/stderr.
 */
async function publishAndOutput(
  client: IApimClient,
  store: IArtifactStore,
  context: ApimServiceContext,
  config: PublishConfig,
  descriptors: ResourceDescriptor[],
  targetDescriptors: ResourceDescriptor[],
  results: PublishActionResult[]
): Promise<void> {
  if (descriptors.length === 0) return;
  const tierResults = await publishTier(client, store, context, config, descriptors, targetDescriptors);
  results.push(...tierResults);
  for (const result of tierResults) {
    outputActionStatus(config, result);
  }
}

/**
 * Separates NamedValue descriptors from all other descriptors in the supplied list.
 *
 * NamedValues must be published before loggers, backends, and other Tier 1
 * resources that may reference them by name in their configuration (e.g. a
 * Logger that stores its instrumentation key as a named value).
 *
 * Auto-generated NamedValues (24-char hex IDs like Logger credentials) are
 * filtered out because APIM recreates them when the referencing Logger is
 * published. Publishing them would create orphan duplicates.
 *
 * However, if the user has provided an explicit override for an auto-generated
 * named value, it is published normally. This supports publishing to fresh
 * environments where APIM cannot recreate the named value automatically.
 */
function splitNamedValues(
  descriptors: ResourceDescriptor[],
  overrides?: OverrideConfig
): { namedValues: ResourceDescriptor[]; otherTier1: ResourceDescriptor[] } {
  const namedValues: ResourceDescriptor[] = [];
  const otherTier1: ResourceDescriptor[] = [];

  for (const descriptor of descriptors) {
    if (descriptor.type === ResourceType.NamedValue) {
      const name = getNamePart(descriptor.nameParts, 0);
      if (isAutoGeneratedId(name) && !hasNamedValueOverride(name, overrides, descriptor.workspace)) {
        logger.debug(`Skipping auto-generated named value: ${name}`);
        continue;
      }
      namedValues.push(descriptor);
    } else {
      otherTier1.push(descriptor);
    }
  }

  return { namedValues, otherTier1 };
}

/**
 * Splits named values into those published before the rest of Tier 1 and
 * those published after the backends, loggers and schemas: a named value that
 * a policy or policy fragment in the source uses as the whole value of a
 * reference attribute (backend-id="{{name}}", logger-id, schema-id), and whose
 * value (with overrides) names a resource of that type published in this
 * tier. APIM checks the policies that use a named value when the named value
 * changes, rejecting the change ("its value breaks policies") while the
 * resource it now names doesn't exist. A backend or logger published here
 * that uses one of those in its credentials is published after it (`after`);
 * when that resource has to go before a later named value too (it is what one
 * names, or a member of a pool here), the named value stays first instead.
 * The policies are read (once) only when a named value's value matches the
 * name of such a resource here; a named value that can't be read goes first,
 * and publishing it reports the error.
 */
async function splitNamedValuesNamingResources(
  store: IArtifactStore,
  config: PublishConfig,
  namedValues: ResourceDescriptor[],
  otherTier1: ResourceDescriptor[],
  namedValueTargets: NamedValueTargetIndex
): Promise<{ early: ResourceDescriptor[]; late: ResourceDescriptor[]; after: ResourceDescriptor[] }> {
  const resourceKey = (type: ResourceType, name: string, workspace: string | undefined) =>
    `${type}/${workspace ?? ''}/${name.toLowerCase()}`;
  const named = new Set(
    otherTier1
      .filter((descriptor) => NAMED_THROUGH_NAMED_VALUE_TYPES.has(descriptor.type))
      .map((descriptor) => resourceKey(descriptor.type, getNamePart(descriptor.nameParts, 0), descriptor.workspace))
  );
  const early: ResourceDescriptor[] = [];
  const late: ResourceDescriptor[] = [];
  if (named.size === 0) {
    return { early: namedValues, late, after: [] };
  }
  // The resources the late named values name, which go before them.
  const lateTargets = new Set<string>();
  // The named values policies use as resource names, and as which types.
  // Every policy in the source counts, not only the ones the filter selects:
  // APIM checks every policy on the target that uses the named value, and
  // this only decides the order, not what is published.
  const typesFor = async (namedValue: ResourceDescriptor): Promise<Set<ResourceType> | undefined> =>
    (await namedValueTargets()).get(getResourceDescriptorKey(namedValue));
  for (const descriptor of namedValues) {
    let isLate = false;
    try {
      const json = await store.readResource(config.sourceDir, descriptor);
      const name = json ? namedValueTargetName(applyOverrides(descriptor, json, config.overrides)) : undefined;
      if (name && [...NAMED_THROUGH_NAMED_VALUE_TYPES].some((type) => named.has(resourceKey(type, name, descriptor.workspace)))) {
        const targets = [...(await typesFor(descriptor) ?? [])]
          .map((type) => resourceKey(type, name, descriptor.workspace))
          .filter((target) => named.has(target));
        targets.forEach((target) => lateTargets.add(target));
        isLate = targets.length > 0;
      }
    } catch {
      isLate = false;
    }
    (isLate ? late : early).push(descriptor);
  }
  if (late.length === 0) {
    return { early, late, after: [] };
  }

  // A backend or logger published here whose own configuration (its
  // credentials) uses one of those named values needs it first: it is
  // published after the late named values, unless it has to go before them,
  // in which case the named value it uses stays early.
  const available = await store.listResources(config.sourceDir);
  const resolve = createArtifactReferenceResolver(available, (descriptor) => store.readResource(config.sourceDir, descriptor));
  const lateKeys = new Set(late.map(getResourceDescriptorKey));
  const users: Array<{ descriptor: ResourceDescriptor; uses: string[] }> = [];
  const poolMembers = new Set<string>();
  for (const descriptor of otherTier1) {
    if (descriptor.type !== ResourceType.Backend && descriptor.type !== ResourceType.Logger) {
      continue;
    }
    let json: Record<string, unknown> | undefined;
    try {
      json = await store.readResource(config.sourceDir, descriptor);
    } catch {
      continue;
    }
    if (!json) {
      continue;
    }
    const resource = { descriptor, json: applyOverrides(descriptor, json, config.overrides) };
    const uses: string[] = [];
    for (const dependency of findTransitiveDependencies(new Map(), new Map(), descriptor.workspace, [resource])) {
      const target = dependency.type === ResourceType.NamedValue ? await resolve(dependency) : undefined;
      if (target && lateKeys.has(getResourceDescriptorKey(target))) {
        uses.push(getResourceDescriptorKey(target));
      }
    }
    if (uses.length > 0) {
      users.push({ descriptor, uses });
    }
    const pool = (resource.json.properties as Record<string, unknown> | undefined)?.pool as Record<string, unknown> | undefined;
    for (const service of Array.isArray(pool?.services) ? pool.services : []) {
      const id = (service as Record<string, unknown> | undefined)?.id;
      const member = typeof id === 'string' ? armNameAfter(id, 'backends') : undefined;
      if (member) {
        poolMembers.add(resourceKey(ResourceType.Backend, member, descriptor.workspace));
      }
    }
  }
  const mustGoFirst = users.filter(({ descriptor }) => {
    const key = resourceKey(descriptor.type, getNamePart(descriptor.nameParts, 0), descriptor.workspace);
    return lateTargets.has(key) || poolMembers.has(key);
  });
  const neededFirst = new Set(mustGoFirst.flatMap(({ uses }) => uses));
  return {
    early: [...early, ...late.filter((descriptor) => neededFirst.has(getResourceDescriptorKey(descriptor)))],
    late: late.filter((descriptor) => !neededFirst.has(getResourceDescriptorKey(descriptor))),
    after: users
      .filter((user) => !mustGoFirst.includes(user) && user.uses.some((use) => !neededFirst.has(use)))
      .map(({ descriptor }) => descriptor),
  };
}

/** Tier 1 types a policy attribute can name through a named value. */
const NAMED_THROUGH_NAMED_VALUE_TYPES: ReadonlySet<ResourceType> = new Set([
  ResourceType.Backend,
  ResourceType.Logger,
  ResourceType.GlobalSchema,
]);

/**
 * Separates Backend descriptors that are pool backends (properties.type === "Pool")
 * from all other descriptors in the supplied list.
 *
 * Pool backends reference individual Backend resources and must therefore be
 * published *after* those backends are created. Reading the artifact JSON is
 * the only reliable way to detect pool backends at publish time because the
 * ResourceType enum treats all backends as the same type.
 */
async function splitPoolBackends(
  store: IArtifactStore,
  sourceDir: string,
  descriptors: ResourceDescriptor[]
): Promise<{ poolBackends: ResourceDescriptor[]; regularTier1: ResourceDescriptor[] }> {
  const poolBackends: ResourceDescriptor[] = [];
  const regularTier1: ResourceDescriptor[] = [];

  for (const descriptor of descriptors) {
    if (descriptor.type === ResourceType.Backend) {
      const json = await store.readResource(sourceDir, descriptor);
      const props = json?.properties as Record<string, unknown> | undefined;
      const backendType = props?.type;
      if (typeof backendType === 'string' && backendType.toLowerCase() === POOL_BACKEND_TYPE) {
        poolBackends.push(descriptor);
        continue;
      }
    }
    regularTier1.push(descriptor);
  }

  return { poolBackends, regularTier1 };
}

async function splitMcpApis(
  store: IArtifactStore,
  sourceDir: string,
  descriptors: ResourceDescriptor[]
): Promise<{ mcpApis: ResourceDescriptor[]; regularTier2: ResourceDescriptor[] }> {
  const mcpApis: ResourceDescriptor[] = [];
  const regularTier2: ResourceDescriptor[] = [];

  for (const descriptor of descriptors) {
    if (descriptor.type === ResourceType.Api) {
      const json = await store.readResource(sourceDir, descriptor);
      const props = json?.properties as Record<string, unknown> | undefined;
      const mcpTools = props?.mcpTools;
      if (Array.isArray(mcpTools) && mcpTools.length > 0) {
        mcpApis.push(descriptor);
        continue;
      }
    }

    regularTier2.push(descriptor);
  }

  return { mcpApis, regularTier2 };
}

/**
 * Publish a single tier of resources in parallel.
 */
async function publishTier(
  client: IApimClient,
  store: IArtifactStore,
  context: ApimServiceContext,
  config: PublishConfig,
  descriptors: ResourceDescriptor[],
  allTargetDescriptors: ResourceDescriptor[]
): Promise<PublishActionResult[]> {
  const publishDescriptor = async (descriptor: ResourceDescriptor): Promise<PublishActionResult[]> => {
    try {
      let publishResult: ResourcePublishResult;
      const apiName = descriptor.type === ResourceType.Api
        ? getNamePart(descriptor.nameParts, 0)
        : undefined;
      const isApiRevision = typeof apiName === 'string' && isApiRevisionName(apiName);

      // Use specialized publishers for Api and Product types
      if (descriptor.type === ResourceType.Api && !isApiRevision) {
        publishResult = await publishApi(
          client,
          store,
          context,
          descriptor,
          config,
          config.filter ? allTargetDescriptors : undefined
        );
      } else if (descriptor.type === ResourceType.Product) {
        publishResult = config.filter
          ? await publishProduct(client, store, context, descriptor, config, allTargetDescriptors)
          : await publishProduct(client, store, context, descriptor, config);
      } else {
        publishResult = await publishResource(
          client,
          store,
          context,
          descriptor,
          config,
          config.filter ? allTargetDescriptors : undefined
        );
      }

      const relatedResults = publishResult.relatedResults?.map(convertToActionResult) ?? [];
      return publishResult.suppressPrimaryResult
        ? relatedResults
        : [convertToActionResult(publishResult), ...relatedResults];
    } catch (error) {
      logger.error(
        `Failed to publish ${buildResourceLabel(descriptor)}:`,
        error
      );
      return [{
        descriptor,
        action: 'put' as const,
        status: 'failed' as const,
        error: error instanceof Error ? error : new Error(String(error)),
      }];
    }
  };

  const tasks = descriptors.map((descriptor) => async () => {
    const { value, retries } = await trackRetries(() => publishDescriptor(descriptor));
    return attachRetries(value, retries);
  });

  const taskResults = await runParallel(tasks, 5);

  return taskResults.flatMap((tr, index) => {
    if (tr.status === 'fulfilled' && tr.value) {
      return tr.value;
    } else {
      // Should not happen given error handling above, but be defensive
      const descriptor = descriptors[index];
      if (!descriptor) {
        throw new Error('No descriptor found for failed task');
      }
      return [{
        descriptor,
        action: 'put' as const,
        status: 'failed' as const,
        error: tr.reason || new Error('Unknown error'),
      }];
    }
  });
}

function filterApiRevisionsHandledByRootApis(
  descriptors: ResourceDescriptor[]
): ResourceDescriptor[] {
  const rootApiKeys = new Set<string>();
  for (const descriptor of descriptors) {
    if (descriptor.type !== ResourceType.Api) {
      continue;
    }

    const apiName = getNamePart(descriptor.nameParts, 0);
    if (!isApiRevisionName(apiName)) {
      rootApiKeys.add(apiScopeKey(descriptor.workspace, apiName));
    }
  }

  if (rootApiKeys.size === 0) {
    return descriptors;
  }

  return descriptors.filter((descriptor) => {
    if (descriptor.type !== ResourceType.Api) {
      return true;
    }

    const apiName = getNamePart(descriptor.nameParts, 0);
    if (!isApiRevisionName(apiName)) {
      return true;
    }

    return !rootApiKeys.has(apiScopeKey(descriptor.workspace, getApiRootName(apiName)));
  });
}

function apiScopeKey(workspace: string | undefined, apiName: string): string {
  return `${workspace ?? ''}:${apiName}`.toLowerCase();
}
/**
 * Execute DELETE operations in reverse dependency order (tier 4 → tier 1).
 */
async function executeDeletes(
  client: IApimClient,
  store: IArtifactStore,
  context: ApimServiceContext,
  config: PublishConfig
): Promise<PublishActionResult[]> {
  const deleteDescriptors = await computeDeleteActions(
    client,
    store,
    context,
    config
  );

  if (deleteDescriptors.length === 0) {
    logger.debug('No resources to delete');
    return [];
  }

  logger.debug(`Deleting ${deleteDescriptors.length} unmatched resources`);

  return executeDeletesForDescriptors(
    client,
    context,
    deleteDescriptors,
    config,
    true
  );
}

/**
 * Execute DELETE operations for a precomputed descriptor list in reverse dependency order.
 */
async function executeDeletesForDescriptors(
  client: IApimClient,
  context: ApimServiceContext,
  deleteDescriptors: ResourceDescriptor[],
  config: PublishConfig,
  descriptorsAreDeployed = false
): Promise<PublishActionResult[]> {
  if (deleteDescriptors.length === 0) {
    logger.debug('No resources to delete');
    return [];
  }

  const results: PublishActionResult[] = [];

  // When a base API is being deleted, the DELETE uses deleteRevisions=true and
  // removes all of its revisions in one call. Drop individual ;rev=N deletes
  // whose base API is also in the delete set to avoid redundant/racy deletes and
  // the "Cannot delete the current revision of an API" error.
  const effectiveDescriptors = filterRevisionDeletesHandledByBaseApi(deleteDescriptors);

  // Group by tier
  const tierGroups = new Map<number, ResourceDescriptor[]>();
  for (const descriptor of effectiveDescriptors) {
    const tier = getResourceTier(descriptor.type);
    if (!tierGroups.has(tier)) {
      tierGroups.set(tier, []);
    }
    tierGroups.get(tier)!.push(descriptor);
  }

  // Execute in REVERSE tier order (4, 3, 2, 1)
  for (const tier of [4, 3, 2, 1]) {
    const descriptors = tierGroups.get(tier) || [];
    if (descriptors.length === 0) continue;

    logger.debug(`Deleting tier ${tier}: ${descriptors.length} resources`);
    const tierStartedAt = Date.now();
    writeTierHeader(config, tier, descriptors.length, 'Delete tier');

    const tierResults = await deleteTier(
      client,
      context,
      descriptors,
      config,
      descriptorsAreDeployed
    );

    results.push(...tierResults);

    // Output per-resource status lines
    for (const result of tierResults) {
      outputActionStatus(config, result);
    }
    writeTierFooter(config, tier, Date.now() - tierStartedAt, 'Delete tier');
  }

  return results;
}

/**
 * Delete a single tier of resources in parallel.
 */
async function deleteTier(
  client: IApimClient,
  context: ApimServiceContext,
  descriptors: ResourceDescriptor[],
  config: PublishConfig,
  descriptorsAreDeployed: boolean
): Promise<PublishActionResult[]> {
  const deleteDescriptor = async (descriptor: ResourceDescriptor): Promise<PublishActionResult> => {
    try {
      const deployedDescriptor = config.envMapping && !descriptorsAreDeployed
        ? mapDescriptor(descriptor, config.envMapping)
        : descriptor;
      const resolvedDescriptor = await resolveAssociationDeleteDescriptor(
        client,
        context,
        deployedDescriptor
      );
      if (!resolvedDescriptor) {
        return {
          descriptor,
          action: 'delete' as const,
          status: 'skipped' as const,
        };
      }
      const deleted = await client.deleteResource(context, resolvedDescriptor);

      return {
        descriptor,
        action: 'delete' as const,
        status: deleted ? ('success' as const) : ('skipped' as const),
      };
    } catch (error) {
      logger.error(
        `Failed to delete ${buildResourceLabel(descriptor)}:`,
        error
      );
      return {
        descriptor,
        action: 'delete' as const,
        status: 'failed' as const,
        error: error instanceof Error ? error : new Error(String(error)),
      };
    }
  };

  const tasks = descriptors.map((descriptor) => async () => {
    const { value, retries } = await trackRetries(() => deleteDescriptor(descriptor));
    return attachRetries([value], retries)[0] ?? value;
  });

  const taskResults = await runParallel(tasks, 5);

  return taskResults.map((tr, index) => {
    if (tr.status === 'fulfilled' && tr.value) {
      return tr.value;
    } else {
      const descriptor = descriptors[index];
      if (!descriptor) {
        throw new Error('No descriptor found for failed task');
      }
      return {
        descriptor,
        action: 'delete' as const,
        status: 'failed' as const,
        error: tr.reason || new Error('Unknown error'),
      };
    }
  });
}

/**
 * Convert ResourcePublishResult to PublishActionResult.
 */
function convertToActionResult(
  result: ResourcePublishResult
): PublishActionResult {
  return {
    descriptor: result.descriptor,
    action: result.action,
    status: result.status,
    error: result.error,
  };
}

/**
 * Attribute the retries recorded for one publish task to the results that
 * incurred them. Retries the client attributed to a specific resource are
 * assigned to the matching result (e.g. an operation published as part of its
 * API); any remaining retries are assigned to the primary (first) result.
 */
function attachRetries(
  results: PublishActionResult[],
  retries: RetryCounts
): PublishActionResult[] {
  if (retries.total === 0 || results.length === 0) {
    return results;
  }

  const unassigned = new Map(retries.byResource);
  let assignedTotal = 0;
  const attributed = results.map((result) => {
    const key = getResourceDescriptorKey(result.descriptor);
    const count = unassigned.get(key);
    if (count === undefined) {
      return result;
    }
    unassigned.delete(key);
    assignedTotal += count;
    return { ...result, retries: count };
  });

  const remainder = retries.total - assignedTotal;
  if (remainder > 0) {
    const primary = attributed[0];
    if (primary) {
      attributed[0] = { ...primary, retries: (primary.retries ?? 0) + remainder };
    }
  }

  return attributed;
}

/**
 * Output per-resource status line to stdout.
 */
function outputActionStatus(config: PublishConfig, result: PublishActionResult): void {
  const verb = result.action.toUpperCase();
  const path = buildResourcePath(result.descriptor);
  const retries = result.retries ?? 0;
  const retrySuffix = retries > 0 ? ` (${retries} ${retries === 1 ? 'retry' : 'retries'})` : '';

  if (result.status === 'success') {
    if (isTextOutput(config)) process.stdout.write(`${verb} ${path}${retrySuffix}\n`);
  } else if (result.status === 'skipped') {
    if (isTextOutput(config)) process.stdout.write(`SKIP ${path}${retrySuffix}\n`);
  } else if (result.status === 'failed') {
    process.stderr.write(`ERROR ${verb} ${path}${retrySuffix}: ${result.error?.message}\n`);
  }
}

/**
 * Build a human-readable path for a resource descriptor.
 */
function buildResourcePath(descriptor: ResourceDescriptor): string {
  const parts: string[] = [descriptor.type.toLowerCase()];

  if (descriptor.workspace) {
    parts.push(`workspace:${descriptor.workspace}`);
  }

  parts.push(...descriptor.nameParts);

  return parts.join('/');
}

/**
 * Determine exit code based on results.
 * Uses standardised constants from exit-codes module.
 */
function determineExitCode(results: PublishActionResult[]): number {
  if (results.length === 0) {
    return EXIT_SUCCESS;
  }

  const successCount = results.filter((r) => r.status === 'success').length;
  const failedCount = results.filter((r) => r.status === 'failed').length;

  if (failedCount === 0) {
    return EXIT_SUCCESS;
  }

  if (successCount > 0) {
    return EXIT_PARTIAL;
  }

  return EXIT_FATAL;
}
